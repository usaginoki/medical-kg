"""Stage `report`: write db/build_report.md (row counts, match rates, evidence mix, orphan checks)."""
import datetime, os

from common import DB_DIR

TABLES = ["source", "dish", "dish_ingredient", "dish_nutrient", "ingredient", "ingredient_alias", "ingredient_xref",
          "ingredient_property", "compound", "compound_xref", "ingredient_compound", "condition", "condition_alias",
          "condition_relation", "compound_condition", "ingredient_condition", "drug", "drug_condition",
          "ingredient_drug"]

# (table, column, referenced table, referenced column)
FKS = [
    ("dish_ingredient", "dish_id", "dish", "dish_id"),
    ("dish_ingredient", "ingredient_id", "ingredient", "ingredient_id"),
    ("dish_nutrient", "dish_id", "dish", "dish_id"),
    ("dish_nutrient", "nutrient_compound_id", "compound", "compound_id"),
    ("ingredient_alias", "ingredient_id", "ingredient", "ingredient_id"),
    ("ingredient_xref", "ingredient_id", "ingredient", "ingredient_id"),
    ("ingredient_property", "ingredient_id", "ingredient", "ingredient_id"),
    ("compound_xref", "compound_id", "compound", "compound_id"),
    ("ingredient_compound", "ingredient_id", "ingredient", "ingredient_id"),
    ("ingredient_compound", "compound_id", "compound", "compound_id"),
    ("condition_alias", "condition_id", "condition", "condition_id"),
    ("condition_relation", "from_id", "condition", "condition_id"),
    ("condition_relation", "to_id", "condition", "condition_id"),
    ("compound_condition", "compound_id", "compound", "compound_id"),
    ("compound_condition", "condition_id", "condition", "condition_id"),
    ("ingredient_condition", "ingredient_id", "ingredient", "ingredient_id"),
    ("ingredient_condition", "condition_id", "condition", "condition_id"),
    ("drug_condition", "drug_id", "drug", "drug_id"),
    ("drug_condition", "condition_id", "condition", "condition_id"),
    ("ingredient_drug", "ingredient_id", "ingredient", "ingredient_id"),
    ("ingredient_drug", "drug_id", "drug", "drug_id"),
]


def md_table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join("" if v is None else (f"{v:,}" if isinstance(v, int) else
                                                      f"{v:.1%}" if isinstance(v, float) and v <= 1 else str(v))
                              for v in r) + " |" for r in rows]
    return "\n".join(out)


def build(con):
    q = lambda sql: con.execute(sql).fetchall()
    out = [f"# Unified database: build report", "",
           f"Generated by `db/build.py` on {datetime.date.today()}. Regenerated on every build.", "",
           "## Row counts", md_table([(t, q(f"SELECT count(*) FROM {t}")[0][0]) for t in TABLES], ["table", "rows"])]

    out += ["", "## Dishes and ingredient matching per source",
            md_table(q("""SELECT d.source_id, count(DISTINCT d.dish_id),
                                 count(di.dish_id),
                                 avg((di.ingredient_id IS NOT NULL)::INT)::DOUBLE,
                                 avg((di.grams IS NOT NULL)::INT)::DOUBLE,
                                 string_agg(DISTINCT d.country_iso2, ' ')
                          FROM dish d LEFT JOIN dish_ingredient di USING (dish_id)
                          GROUP BY 1 ORDER BY 2 DESC"""),
                     ["source", "dishes", "ingredient lines", "matched", "with grams", "countries"]),
            "", "Match methods:",
            md_table(q("SELECT match_method, count(*) FROM dish_ingredient GROUP BY 1 ORDER BY 2 DESC"),
                     ["match_method", "lines"])]

    out += ["", "## Top unmatched ingredient strings",
            md_table(q("""SELECT d.lang, di.raw_text, count(*) n FROM dish_ingredient di JOIN dish d USING (dish_id)
                          WHERE di.ingredient_id IS NULL GROUP BY 1, 2 ORDER BY n DESC LIMIT 25"""),
                     ["lang", "raw_text", "lines"])]

    out += ["", "## Conditions by type and vocabulary",
            md_table(q("SELECT type, source_vocab, count(*) FROM condition GROUP BY 1, 2 ORDER BY 3 DESC"),
                     ["type", "source_vocab", "conditions"])]

    for t in ["compound_condition", "ingredient_condition", "ingredient_compound"]:
        cols = "source_id, evidence_type" + (", direction" if t != "ingredient_compound" else "")
        hdr = ["source", "evidence"] + (["direction"] if t != "ingredient_compound" else [])
        out += ["", f"## `{t}` by source and evidence",
                md_table(q(f"SELECT {cols}, count(*) FROM {t} GROUP BY ALL ORDER BY count(*) DESC"), hdr + ["rows"])]

    # computed with semi-joins on the roll-up (same result as scanning v_dish_condition, which is ~10^8 rows)
    out += ["", "## Reachability",
            md_table(q("""WITH ing_c AS (
                   SELECT r.ingredient_id, r.condition_id, c.type FROM ingredient_condition_rollup r
                   JOIN condition c USING (condition_id)),
                 nut_c AS (
                   SELECT dn.dish_id, cc.condition_id, c.type FROM dish_nutrient dn
                   JOIN compound_condition cc ON cc.compound_id = dn.nutrient_compound_id JOIN condition c USING (condition_id)),
                 dish_any AS (
                   SELECT dish_id FROM dish_ingredient WHERE ingredient_id IN (SELECT ingredient_id FROM ing_c)
                   UNION SELECT dish_id FROM nut_c),
                 dish_sym AS (
                   SELECT dish_id FROM dish_ingredient
                   WHERE ingredient_id IN (SELECT ingredient_id FROM ing_c WHERE type = 'symptom')
                   UNION SELECT dish_id FROM nut_c WHERE type = 'symptom'),
                 cond AS (
                   SELECT condition_id, type FROM ing_c WHERE ingredient_id IN (SELECT ingredient_id FROM dish_ingredient)
                   UNION SELECT condition_id, type FROM nut_c)
                 SELECT (SELECT count(*) FROM dish_any), (SELECT count(*) FROM dish_sym), (SELECT count(*) FROM dish),
                        (SELECT count(*) FROM cond), (SELECT count(*) FROM cond WHERE type = 'symptom')"""),
                     ["dishes with ≥1 condition", "dishes with ≥1 symptom", "dishes", "conditions reached from dishes",
                      "of which symptoms"])]

    orphans = []
    for t, c, rt, rc in FKS:
        n = q(f"SELECT count(*) FROM {t} WHERE {c} IS NOT NULL AND {c} NOT IN (SELECT {rc} FROM {rt})")[0][0]
        orphans.append((f"{t}.{c} → {rt}", n))
    bad = [o for o in orphans if o[1]]
    out += ["", "## Orphan foreign keys", "None ✅" if not bad else md_table(bad, ["reference", "orphan rows"])]

    unknown_src = q("""SELECT DISTINCT t.s FROM (
        SELECT source_id s FROM dish UNION SELECT source_id FROM compound_condition
        UNION SELECT source_id FROM ingredient_condition UNION SELECT source_id FROM ingredient_compound
        UNION SELECT source_id FROM ingredient_drug) t WHERE t.s NOT IN (SELECT source_id FROM source)""")
    out += ["", "Unregistered source ids: " + (", ".join(r[0] for r in unknown_src) if unknown_src else "none ✅")]

    open(os.path.join(DB_DIR, "build_report.md"), "w").write("\n".join(out) + "\n")
    print(f"  orphan references: {sum(n for _, n in orphans):,}; wrote db/build_report.md")
